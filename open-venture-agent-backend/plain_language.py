"""Shared plain-language guidance for founder-facing Gemini prompts."""

PLAIN_LANGUAGE_BLOCK = (
    "PLAIN LANGUAGE — write for a non-technical small business owner with no "
    "background in research, data analysis, or business jargon.\n"
    "- Use short sentences and everyday words.\n"
    "- Prefer concrete examples over abstractions.\n"
    "- Avoid consulting-style vocabulary such as: leverage, optimize, synergy, "
    "market saturation, demographic, stakeholder, value proposition, "
    "go-to-market, underserved segment, competitive landscape, actionable "
    "insights, or similar buzzwords.\n"
    "- If a simpler word works, use it (e.g. \"customers\" not \"demographics\", "
    "\"nearby shops\" not \"competitive landscape\", \"make money\" / \"charge\" "
    "not \"monetize\").\n\n"
    "Before → after (follow this pattern everywhere):\n"
    "1. BEFORE: \"Leverage underserved demographics to optimize your value "
    "proposition in a saturated market.\"\n"
    "   AFTER: \"Focus on people nearby who still can't get what they want from "
    "the shops that are already open.\"\n"
    "2. BEFORE: \"Stakeholders should validate demand signals before capital "
    "allocation.\"\n"
    "   AFTER: \"Before you spend much money, talk to a few possible customers "
    "and see if they would actually buy.\"\n"
    "3. BEFORE: \"Differentiate via superior unit economics and operational "
    "synergies.\"\n"
    "   AFTER: \"Win by keeping costs simple — for example, start with fewer "
    "menu items or products so you waste less and stay easier to run.\"\n"
    "4. BEFORE: \"Address market saturation through niche positioning and "
    "omnichannel acquisition.\"\n"
    "   AFTER: \"There are already a lot of similar places, so pick one clear "
    "thing you're better at — and tell people about it on WhatsApp or Instagram, "
    "not just a fancy website.\"\n"
)
